        public let name: String
        public let platform: AccountDevicePlatform
        public let chip: String?
    }

    public static func model(for identifier: String?) -> Model? {
        guard let identifier else { return nil }
        let key = identifier.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard let name = names[key] else { return nil }
        let platform: AccountDevicePlatform = key.hasPrefix("ipad") ? .iPadOS
            : (key.hasPrefix("iphone") || key.hasPrefix("ipod") ? .iOS : .macOS)
        return Model(name: name, platform: platform, chip: chips[key])
    }

    public static func displayName(for rawModel: String?) -> String? {
        guard let raw = rawModel?.trimmingCharacters(in: .whitespacesAndNewlines),
              !raw.isEmpty else { return nil }
        return model(for: raw)?.name ?? raw
    }

