def emit_csharp(spec: dict) -> str:
    layout = spec["layout"]
    materials = spec["materials"]
    motion = spec["motion"]
    typography = spec["typography"]
    palette = spec["palette"]
    navigation = spec["navigation"]

    lines = [
        "// Generated by Scripts/generate_visual_parity_assets.py. Do not edit by hand.",
        "namespace Skybridge.WinClient.VisualParity;",
        "",
        "internal static class GeneratedVisualParity",
        "{",
        "    internal static class Layout",
        "    {",
    ]
    for key, value in layout.items():
        name = "".join(part.capitalize() for part in key.split("_")) if "_" in key else key[0].upper() + key[1:]
        lines.append(f"        public const double {name} = {csharp_literal(value)};")
    lines += [
        "    }",
        "",
        "    internal static class Materials",
        "    {",
    ]
    for key, value in materials.items():
        name = "".join(part.capitalize() for part in key.split("_")) if "_" in key else key[0].upper() + key[1:]
        lines.append(f"        public const double {name} = {csharp_literal(value)};")
    lines += [
        "    }",
        "",
        "    internal static class Motion",
        "    {",
    ]
    for key, value in motion.items():
        name = "".join(part.capitalize() for part in key.split("_")) if "_" in key else key[0].upper() + key[1:]
        lines.append(f"        public const double {name} = {csharp_literal(value)};")
    lines += [
        "    }",
        "",
        "    internal static class Typography",
        "    {",
    ]
    for key, value in typography.items():
        name = "".join(part.capitalize() for part in key.split("_")) if "_" in key else key[0].upper() + key[1:]
        lines.append(f"        public const double {name} = {csharp_literal(value)};")
    lines += [
        "    }",
        "",
        "    internal static class Palette",
        "    {",
    ]
    for key, value in palette.items():
        name = "".join(part.capitalize() for part in key.split("_")) if "_" in key else key[0].upper() + key[1:]
        if isinstance(value, list):
            joined = ", ".join(f"\"{item}\"" for item in value)
            lines.append(f"        public static readonly string[] {name} = new[] {{ {joined} }};")
        else:
            lines.append(f"        public const string {name} = {csharp_literal(value)};")
    lines += [
        "    }",
        "",
        "    internal static class Navigation",
        "    {",
        f"        public static readonly string[] PrimaryOrder = new[] {{ {', '.join(csharp_literal(v) for v in navigation['primaryOrder'])} }};",
        f"        public static readonly string[] SecondaryOrder = new[] {{ {', '.join(csharp_literal(v) for v in navigation['secondaryOrder'])} }};",
        "    }",
        "}",
    ]
    return "\n".join(lines)


