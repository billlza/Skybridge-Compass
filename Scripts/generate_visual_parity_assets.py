def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--spec",
        type=Path,
        default=Path("Docs/mac-baseline/ui-baseline/visual-spec.json"),
    )
    parser.add_argument(
        "--swift-out",
        type=Path,
        default=Path("Sources/SkyBridgeVisualParity/GeneratedVisualParity.swift"),
    )
    parser.add_argument(
        "--windows-cs-out",
        type=Path,
        required=True,
    )
    parser.add_argument(
        "--windows-xaml-out",
        type=Path,
        required=True,
    )
    args = parser.parse_args()

    spec = load_spec(args.spec)
    write_text(args.swift_out, emit_swift(spec))
    write_text(args.windows_cs_out, emit_csharp(spec))
    write_text(args.windows_xaml_out, emit_xaml(spec))


if __name__ == "__main__":
    main()
